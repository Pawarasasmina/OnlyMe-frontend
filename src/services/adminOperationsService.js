import api from "../api/axiosInstance";
export const adminOperationsService = {
  dashboard: () => api.get("/admin/operations/dashboard"),
  reports: (params = {}) => api.get("/admin/reports", { params }),
  report: (model, id) => api.get(`/admin/reports/${model}/${id}`),
  actionReport: (model, id, payload) => api.post(`/admin/reports/${model}/${id}/action`, payload),
  appeals: (params = {}) => api.get("/admin/appeals", { params }),
  reviewAppeal: (id, payload) => api.post(`/admin/appeals/${id}/review`, payload),
  policy: () => api.get("/admin/moderation-policy"),
  updatePolicy: (payload) => api.put("/admin/moderation-policy", payload),
  user: (id) => api.get(`/admin/users/${id}/investigation`),
  enforceUser: (id, payload) => api.post(`/admin/users/${id}/enforce`, payload),
  audit: (params = {}) => api.get("/admin/audit-log", { params }),
  governanceTargets: (params) => api.get("/admin/governance/targets", { params }),
  exportHistory: (params) => api.get(params.type === "CONTENT" ? "/admin/exports/content" : "/admin/exports/history", { params }),
  exportUserPackage: (params) => api.get("/admin/exports/user-package", { params }),
  createHold: (payload) => api.post("/admin/legal-holds", payload),
  holds: (params = {}) => api.get("/admin/legal-holds", { params }),
  releaseHold: (id, payload) => api.post(`/admin/legal-holds/${id}/release`, payload),
  financialUser: (id) => api.get(`/admin/finance/users/${id}`),
  holdPayouts: (id, reason) => api.post(`/admin/finance/users/${id}/payout-hold`, { reason }),
  releasePayouts: (id, reason) => api.post(`/admin/finance/users/${id}/payout-release`, { reason }),
  refundWorld: (id, payload) => api.post(`/admin/world-entitlements/${id}/refund`, payload),
  refundMembership: (id, payload) => api.post(`/admin/premium-memberships/${id}/refund-current-period`, payload),
};
