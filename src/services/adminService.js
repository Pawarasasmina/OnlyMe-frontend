import axiosInstance from "../api/axiosInstance";

export const adminService = {
  getMyAccess: () => axiosInstance.get("/admin/access/me"),
  getRolePolicies: () => axiosInstance.get("/admin/access/roles"),
  updateRolePolicy: (role, payload) => axiosInstance.put(`/admin/access/roles/${role}`, payload),
  getDashboard: () => axiosInstance.get("/admin/dashboard"),
  getStaff: () => axiosInstance.get("/admin/staff"),
  createStaff: (payload) => axiosInstance.post("/admin/staff", payload),
  updateStaff: (id, payload) => axiosInstance.patch(`/admin/staff/${id}`, payload),
  resetStaffPassword: (id, payload) => axiosInstance.post(`/admin/staff/${id}/reset-password`, payload),
  updateStaffTwoFactor: (id, payload) => axiosInstance.post(`/admin/staff/${id}/2fa`, payload),
  updateRoleTwoFactor: (payload) => axiosInstance.post("/admin/staff/2fa-policy", payload),
  deleteTestStaff: (id, payload) => axiosInstance.delete(`/admin/staff/${id}`, { data: payload }),
  getUsers: (params = {}) => axiosInstance.get("/admin/users", { params }),
  updateUserStatus: (userId, status, reason) => axiosInstance.patch(`/admin/users/${userId}/status`, { status, reason, confirmed: true }),
  bulkUpdateUsers: (payload) => axiosInstance.patch("/admin/users/bulk", payload),
  getMessageReports: (params) => axiosInstance.get("/admin/message-reports", { params }),
  getReportedMessageUsers: () => axiosInstance.get("/admin/message-report-users"),
  getReportedMessageUser: (userId) => axiosInstance.get(`/admin/message-report-users/${userId}`),
  startMessageReportReview: (reportId) => axiosInstance.post(`${window.location.pathname === "/admin/post-reports" ? "/admin/post-reports" : "/admin/user-reports"}/${reportId}/review`),
  startActualMessageReportReview: (reportId) => axiosInstance.post(`/admin/message-reports/${reportId}/review`),
  resolveMessageReport: (reportId, payload) => axiosInstance.post(`/admin/message-reports/${reportId}/resolve`, payload),
  getReportedUsers: () => axiosInstance.get("/admin/user-report-users"),
  getReportedUser: (userId) => axiosInstance.get(`/admin/user-report-users/${userId}`),
  startUserReportReview: (reportId) => axiosInstance.post(`/admin/user-reports/${reportId}/review`),
  resolveUserReport: (reportId, payload) => axiosInstance.post(`/admin/user-reports/${reportId}/resolve`, payload),
  getReportedPostUsers: () => axiosInstance.get("/admin/post-report-users"),
  getReportedPostUser: (userId) => axiosInstance.get(`/admin/post-report-users/${userId}`),
  startPostReportReview: (reportId) => axiosInstance.post(`/admin/post-reports/${reportId}/review`),
  resolvePostReport: (reportId, payload) => axiosInstance.post(`/admin/post-reports/${reportId}/resolve`, payload),
  getUserReports: () => axiosInstance.get("/admin/user-reports", { params: { limit: 100 } }),
  getPostReports: () => axiosInstance.get("/admin/post-reports", { params: { limit: 100 } }),
  getReportDetail: (type, reportId) => axiosInstance.get(`/admin/${type}-reports/${reportId}`),
  getGifts: () => axiosInstance.get("/admin/gifts"),
  createGiftCategory: (name) => axiosInstance.post("/admin/gift-categories", { name }),
  updateGiftCategory: (id, payload) => axiosInstance.patch(`/admin/gift-categories/${id}`, payload),
  reorderGiftCategories: (ids) => axiosInstance.patch("/admin/gift-categories/reorder", { ids }),
  deleteGiftCategory: (id) => axiosInstance.delete(`/admin/gift-categories/${id}`),
  createGift: (formData, onUploadProgress) => axiosInstance.post("/admin/gifts", formData, { onUploadProgress }),
  updateGift: (id, formData, onUploadProgress) => axiosInstance.patch(`/admin/gifts/${id}`, formData, { onUploadProgress }),
  reorderGifts: (ids) => axiosInstance.patch("/admin/gifts/reorder", { ids }),
  deleteGift: (id) => axiosInstance.delete(`/admin/gifts/${id}`),
  getRecommendationExclusions: () => axiosInstance.get("/admin/recommendations/exclusions"),
  searchRecommendationTargets: (params, options = {}) => axiosInstance.get("/admin/recommendations/targets", { ...options, params }),
  setRecommendationExclusion: (payload) => axiosInstance.put("/admin/recommendations/exclusions", payload),
  previewRecommendations: (params) => axiosInstance.get("/admin/recommendations/preview", { params, timeout: 60000 }),
  getRecommendationSettings: () => axiosInstance.get("/admin/recommendations"),
  createRecommendationDraft: (payload) => axiosInstance.post("/admin/recommendations/drafts", payload),
  activateRecommendationConfig: (id) => axiosInstance.post(`/admin/recommendations/${id}/activate`),
  resetRecommendationConfig: () => axiosInstance.post("/admin/recommendations/reset"),
};


